class FontMetrics:
    def __init__(self, alias: str):
        upm, cap, descent, *chunks = _METRICS[alias]
        self.alias = alias
        self.upm = upm
        self.cap = cap
        self.descent = descent
        self.glyphs: dict[int, tuple[int, Optional[tuple[int, int, int, int]]]] = {}
        for ent in "".join(chunks).split(";"):
            if not ent:
                continue
            cp, rest = ent.split(":")
            vals = [int(v) for v in rest.split(",")]
            self.glyphs[int(cp)] = (vals[0], tuple(vals[1:5]) if len(vals) == 5 else None)  # type: ignore

    def glyph(self, ch: str):
        g = self.glyphs.get(ord(ch))
        if g is None:  # not in the table (fallback glyph in AutoCAD): assume an em-square "M"
            g = self.glyphs[ord("M")]
        return g


@lru_cache(maxsize=None)
def metrics(font: str) -> FontMetrics:
    """Metrics by FONTS.md alias ("sans") or STYLE file name ("LiberationSans-Regular.ttf")."""
    return FontMetrics(FONT_ALIAS.get(font, font))


_PCT = re.compile(r"%%(\d{1,3}|[cdpuok%])", re.IGNORECASE)
_UNI = re.compile(r"\[Uu]\+([0-9A-Fa-f]{4})")


def plain(text: str) -> str:
    """Approximate rendered characters of a TEXT value (for measuring only)."""
    text = _UNI.sub(lambda m: chr(int(m.group(1), 16)), text)

    def pct(m: re.Match) -> str:
        c = m.group(1).lower()
        if c.isdigit():
            n = int(c)
            return chr(n) if 32 <= n < 0x110000 else ""
        return {"c": "\u00d8", "d": "\u00b0", "p": "\u00b1", "%": "%"}.get(c, "")

    return _PCT.sub(pct, text)


def text_box(text: str, font: str, h: float, w: float = 1.0) -> tuple[float, float, float, float]:
    """(x0, x1, ink_ymin, ink_ymax) of a TEXT string in drawing units, baseline-left at 0,0."""
    fm = metrics(font)
    s = h / fm.cap
    pen = 0.0
    ink = [math.inf, -math.inf, math.inf, -math.inf]
    for ch in plain(text):
        adv, bb = fm.glyph(ch)
        if bb:
            ink[0] = min(ink[0], pen + bb[0])
            ink[1] = max(ink[1], pen + bb[1])
            ink[2] = min(ink[2], bb[2])
            ink[3] = max(ink[3], bb[3])
        pen += adv
    if ink[0] == math.inf:  # no ink (spaces only / empty)
        ink = [0.0, 0.0, 0.0, 0.0]
    x0 = min(0.0, ink[0]) * s * w
    x1 = max(pen, ink[1]) * s * w
    return x0, x1, ink[2] * s, ink[3] * s


def anchor_offset(text: str, font: str, h: float, w: float, halign: int, valign: int) -> tuple[float, float]:
    """Alignment point relative to the baseline start in the (unmirrored) text frame."""
    x0, x1, y0, y1 = text_box(text, font, h, w)
    if halign == 4:  # MIDDLE: centre of the box / ink box
        return (x0 + x1) / 2, (y0 + y1) / 2
    ax = {0: 0.0, 1: (x0 + x1) / 2, 2: x1}.get(halign, 0.0)
    if halign in (3, 5):
        ax = 0.0
    ay = {0: 0.0, 1: -metrics(font).descent * h / metrics(font).cap, 2: h / 2, 3: h}.get(valign, 0.0)
    return ax, ay


def r(v: float) -> float:
    return round(v, 9) + 0.0


def placement(
    text: str,
    p: Sequence[float],
    align: str = "LEFT",
    h: float = 10.0,
    font: str = "sans",
    style: str = "Standard",
    rotation: float = 0.0,
    width: float = 1.0,
    oblique: float = 0.0,
    flags: int = 0,
    p2: Optional[Sequence[float]] = None,
) -> dict[str, Any]:
    """DXF attributes for a TEXT/ATTRIB/ATTDEF with AutoCAD-consistent 10/11/40/41/50.

    ``p`` is the alignment point (LEFT: insertion point; FIT/ALIGNED: first point, ``p2`` the
    second). ``font`` must be the style's font (alias or file name) for the 10 computation."""
    halign, valign = ALIGN[align]
    d: dict[str, Any] = {"height": h, "style": style}
    if rotation:
        d["rotation"] = rotation
    if width != 1.0:
        d["width"] = width
    if oblique:
        d["oblique"] = oblique
    if flags:
        d["text_generation_flag"] = flags
    px, py = float(p[0]), float(p[1])
    pz = float(p[2]) if len(p) > 2 else 0.0
    if halign in (3, 5):
        if p2 is None:
            raise ValueError("FIT/ALIGNED need p2")
        dx, dy = p2[0] - px, p2[1] - py
        dist = math.hypot(dx, dy)
        x0, x1, _, _ = text_box(text, font, 1.0, 1.0)
        if dist > 0:
            d["rotation"] = r(math.degrees(math.atan2(dy, dx)) % 360.0)
            if halign == 5:  # FIT: height kept, width factor computed
                d["width"] = r(dist / ((x1 - x0) * h))
            else:  # ALIGNED: width factor kept, height computed
                d["height"] = r(dist / ((x1 - x0) * width))
        d.update(insert=(r(px), r(py), pz), align_point=(r(p2[0]), r(p2[1]), pz), halign=halign)
        return d
    if halign == 0 and valign == 0:
        d["insert"] = (r(px), r(py), pz)
        return d
    ax, ay = anchor_offset(text, font, h, width, halign, valign)
    sx = -1.0 if flags & 2 else 1.0
    sy = -1.0 if flags & 4 else 1.0
    ox, oy = -ax * sx, -ay * sy
    a = math.radians(rotation)
    ix = px + ox * math.cos(a) - oy * math.sin(a)
    iy = py + ox * math.sin(a) + oy * math.cos(a)
    d.update(insert=(r(ix), r(iy), pz), align_point=(r(px), r(py), pz))
    if halign:
        d["halign"] = halign
    if valign:
        d["valign"] = valign
    return d


def add_text(layout, text: str, p: Sequence[float], dxfattribs: Optional[dict[str, Any]] = None, **kw: Any):
    """TEXT with :func:`placement`; extra ``dxfattribs`` (layer, color, ...) are merged."""
    d = placement(text, p, **kw)
    if dxfattribs:
        d.update(dxfattribs)
    return layout.add_text(text, dxfattribs=d)


def cross(layout, p: Sequence[float], size: float = 3.0, layer: str = "REF") -> None:
    """Small reference cross (hairline LINEs) at ``p``."""
    x, y = p[0], p[1]
    layout.add_line((x - size, y), (x + size, y), dxfattribs={"layer": layer})
    layout.add_line((x, y - size), (x, y + size), dxfattribs={"layer": layer})


def ref_layer(c, name: str = "REF") -> str:
    return c.layer(name, color=8, lineweight=0)
