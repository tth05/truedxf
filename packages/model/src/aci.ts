/**
 * Palette used for plots. UNVERIFIED (Q-0193, Q-0194): whether PLOT uses this set or the
 * background-adjusted darker set (and adjusts grays 8/9/250–255 for white paper) is open.
 */
export const PLOT_PALETTE: readonly number[] = ACI_PALETTE_LIGHT;

export type Paper = "white" | "black";

/**
 * RGB (0xRRGGBB) of an ACI 1…255. ACI 7 is the foreground color: black on white paper, white on
 * black (note 06 §3.4; UNVERIFIED Q-0195). ACI 255 stays white (Q-0196). Out-of-range values
 * (0, 256, 257, negative) are treated as 7.
 */
export function aciToRgb(
  aci: number,
  palette: readonly number[] = PLOT_PALETTE,
  paper: Paper = "white",
): number {
  const a = Math.trunc(Math.abs(aci));
  if (a === 7 || a < 1 || a > 255) return paper === "white" ? 0x000000 : 0xffffff;
  return palette[a]!;
}

/** Nearest ACI 1…255 (excluding 7) of an RGB, by squared RGB distance; ties → lowest index. */
export function nearestAci(rgb: number, palette: readonly number[] = PLOT_PALETTE): number {
  const r = (rgb >> 16) & 255;
  const g = (rgb >> 8) & 255;
  const b = rgb & 255;
  let best = 1;
  let bestD = Number.POSITIVE_INFINITY;
  for (let i = 1; i < 256; i++) {
    if (i === 7) continue;
    const p = palette[i]!;
    const dr = ((p >> 16) & 255) - r;
    const dg = ((p >> 8) & 255) - g;
    const db = (p & 255) - b;
    const d = dr * dr + dg * dg + db * db;
    if (d < bestD) {
      bestD = d;
      best = i;
    }
  }
  return best;
}
