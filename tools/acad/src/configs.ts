// Generates the dedicated truedxf plot configs from the user's installed AutoCAD originals:
//   Plotters/truedxf PNG.pc3 + Plotters/PMP Files/truedxf PNG.pmp   (from PublishToWeb PNG.pc3/.pmp)
//   Plotters/truedxf PDF.pc3 + Plotters/PMP Files/truedxf PDF.pmp   (from DWG To PDF.pc3)
// Autodesk files are never copied into the repo (AGENTS.md); only this generator is committed.
// Existing user configs are never modified; our four files are (re)written.
//
//   node tools/acad/src/configs.ts [--dry-run] [--dump]
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { PLOT_STYLES_DIR, PLOTTERS_DIR, PMP_DIR, requireFile } from "./env.ts";
import {
    bool,
    decodePia,
    encodePia,
    formatPiaText,
    num,
    type PiaNode,
    parsePiaText,
    piaGet,
    piaSet,
    sec,
    str,
    val,
} from "./pia.ts";
import {
    CANVASES,
    type Canvas,
    PDF_PC3,
    PDF_PMP,
    PNG_PC3,
    PNG_PMP,
    pdfPaperName,
    pngPaperName,
} from "./sizes.ts";

const DESCRIPTION = "truedxf reference harness (generated by tools/acad/src/configs.ts)";

function read(path: string): PiaNode[] {
    return parsePiaText(decodePia(readFileSync(requireFile(path, "AutoCAD config"))).text);
}

const f2 = (x: number) => x.toFixed(2);

// ---------------------------------------------------------------- raster (PNG)

function rasterSize([w, h]: Canvas, i: number) {
    // Raster printable bounds are inclusive pixel indices: zero margins = (0,0)x(w-1,h-1), exactly as
    // in the user sizes of the stock PublishToWeb PNG.pmp.
    const canon = `UserDefinedRaster (${f2(w)} x ${f2(h)}Pixels)`;
    const descName = `UserDefinedRaster Landscape ${f2(w)}W x ${f2(h)}H - (0, 0) x (${w - 1}, ${h - 1}) =${w * h} Pixels`;
    const size = sec(String(i), [
        val("caps_type", "2"),
        val("name", str(canon)),
        val("localized_name", str(pngPaperName([w, h]))),
        val("media_description_name", str(descName)),
        val("media_group", "16"),
        val("landscape_mode", bool(true)),
    ]);
    const desc = sec(String(i), [
        val("caps_type", "2"),
        val("name", str(descName)),
        val("media_bounds_urx", num(w)),
        val("media_bounds_ury", num(h)),
        val("printable_bounds_llx", num(0)),
        val("printable_bounds_lly", num(0)),
        val("printable_bounds_urx", num(w - 1)),
        val("printable_bounds_ury", num(h - 1)),
        val("printable_area", num((w - 1) * (h - 1))),
        val("dimensional", bool(false)),
    ]);
    return { size, desc, canon };
}

function buildPngPmp(stockPmp: PiaNode[], pmpPath: string): PiaNode[] {
    const meta = structuredClone(piaGet(stockPmp, "meta")!);
    piaSet(meta.children!, "user_defined_model_pathname", str(pmpPath));
    const mediaCaps = piaGet(stockPmp, "udm/media")!.children!.filter((n) => !n.children);
    const sizes = CANVASES.map(rasterSize);
    return [
        meta,
        structuredClone(piaGet(stockPmp, "mod")!),
        structuredClone(piaGet(stockPmp, "del")!),
        sec("udm", [
            structuredClone(piaGet(stockPmp, "udm/calibration")!),
            sec("media", [
                ...structuredClone(mediaCaps),
                sec(
                    "size",
                    sizes.map((s) => s.size),
                ),
                sec(
                    "description",
                    sizes.map((s) => s.desc),
                ),
            ]),
        ]),
        structuredClone(piaGet(stockPmp, "hidden")!),
    ];
}

function setDefaultMedia(
    pc3: PiaNode[],
    name: string,
    w: number,
    h: number,
    pUrx: number,
    pUry: number,
    dimensional: boolean,
) {
    piaSet(pc3, "media/actual_printable_bounds_llx", num(0));
    piaSet(pc3, "media/actual_printable_bounds_lly", num(0));
    piaSet(pc3, "media/actual_printable_bounds_urx", num(pUrx));
    piaSet(pc3, "media/actual_printable_bounds_ury", num(pUry));
    piaSet(pc3, "media/size/name", str(name.replaceAll(" ", "_")));
    piaSet(pc3, "media/size/group", dimensional ? "15" : "16");
    piaSet(pc3, "media/size/landscape_mode", bool(true));
    const md = "media/size/media_description";
    piaSet(pc3, `${md}/printable_bounds_llx`, num(0));
    piaSet(pc3, `${md}/printable_bounds_lly`, num(0));
    piaSet(pc3, `${md}/printable_bounds_urx`, num(pUrx));
    piaSet(pc3, `${md}/printable_bounds_ury`, num(pUry));
    piaSet(pc3, `${md}/printable_area`, num(pUrx * pUry));
    piaSet(pc3, `${md}/dimensional`, bool(dimensional));
    piaSet(pc3, `${md}/media_bounds/urx`, num(w));
    piaSet(pc3, `${md}/media_bounds/ury`, num(h));
}

function buildPngPc3(stockPc3: PiaNode[], pmpPath: string): PiaNode[] {
    const pc3 = structuredClone(stockPc3);
    piaSet(pc3, "meta/user_defined_model_pathname", str(pmpPath));
    piaSet(pc3, "meta/user_defined_model_basename", str(PNG_PMP));
    piaSet(pc3, "meta/config_description", str(DESCRIPTION));
    const [w, h] = CANVASES[0]!;
    setDefaultMedia(pc3, rasterSize([w, h], 0).canon, w, h, w - 1, h - 1, false);
    // White background (16777215 = 0xFFFFFF), as in the stock config; pinned so edits can't leak in.
    const custom = piaGet(pc3, "custom")!.children!;
    const bg = custom.find((c) =>
        c.children?.some((n) => n.key === "name" && n.value === str("RASTER_RGB_Back_Color")),
    );
    if (!bg) throw new Error("stock PNG pc3 has no RASTER_RGB_Back_Color");
    piaSet(bg.children!, "value", "16777215");
    return pc3;
}

// ---------------------------------------------------------------- vector (PDF)

function pdfSize([w, h]: Canvas, i: number) {
    // Sheet = canvas / 100 dpi inches, stored in mm like the stock DWG To PDF.pc3 media bounds.
    const win = w / 100;
    const hin = h / 100;
    const wmm = win * 25.4;
    const hmm = hin * 25.4;
    const canon = `UserDefinedImperial (${f2(win)} x ${f2(hin)}Inches)`;
    const descName = `UserDefinedImperial Landscape ${f2(win)}W x ${f2(hin)}H - (0, 0) x (${f2(win)}, ${f2(hin)}) =${f2(win * hin)} Inches`;
    const size = sec(String(i), [
        val("caps_type", "2"),
        val("name", str(canon)),
        val("localized_name", str(pdfPaperName([w, h]))),
        val("media_description_name", str(descName)),
        val("media_group", "15"),
        val("landscape_mode", bool(true)),
    ]);
    const desc = sec(String(i), [
        val("caps_type", "2"),
        val("name", str(descName)),
        val("media_bounds_urx", num(wmm)),
        val("media_bounds_ury", num(hmm)),
        val("printable_bounds_llx", num(0)),
        val("printable_bounds_lly", num(0)),
        val("printable_bounds_urx", num(wmm)),
        val("printable_bounds_ury", num(hmm)),
        val("printable_area", num(wmm * hmm)),
        val("dimensional", bool(true)),
    ]);
    return { size, desc, canon, wmm, hmm };
}

function buildPdfPmp(stockPdfPc3: PiaNode[], stockPngPmp: PiaNode[], pmpPath: string): PiaNode[] {
    const meta = structuredClone(piaGet(stockPdfPc3, "meta")!);
    piaSet(meta.children!, "user_defined_model_pathname", str(pmpPath));
    meta.children = meta.children!.filter((n) => !["config_description", "config_autospool"].includes(n.key));
    // The media ability flags are driver-generic; the PNG PMP ones are reused (verified by listing).
    const mediaCaps = piaGet(stockPngPmp, "udm/media")!.children!.filter((n) => !n.children);
    const sizes = CANVASES.map(pdfSize);
    return [
        meta,
        structuredClone(piaGet(stockPngPmp, "mod")!),
        structuredClone(piaGet(stockPngPmp, "del")!),
        sec("udm", [
            structuredClone(piaGet(stockPngPmp, "udm/calibration")!),
            sec("media", [
                ...structuredClone(mediaCaps),
                sec(
                    "size",
                    sizes.map((s) => s.size),
                ),
                sec(
                    "description",
                    sizes.map((s) => s.desc),
                ),
            ]),
        ]),
        structuredClone(piaGet(stockPngPmp, "hidden")!),
    ];
}

function buildPdfPc3(stockPc3: PiaNode[], pmpPath: string): PiaNode[] {
    const pc3 = structuredClone(stockPc3);
    piaSet(pc3, "meta/user_defined_model_pathname", str(pmpPath));
    piaSet(pc3, "meta/user_defined_model_basename", str(PDF_PMP));
    piaSet(pc3, "meta/config_description", str(DESCRIPTION));
    const s = pdfSize(CANVASES[0]!, 0);
    setDefaultMedia(pc3, s.canon, s.wmm, s.hmm, s.wmm, s.hmm, true);
    // Keep geometry as vectors and do not open a viewer after plotting.
    const custom = piaGet(pc3, "custom")!.children!;
    const setCustom = (name: string, value: string) => {
        const c = custom.find((x) => x.children?.some((n) => n.key === "name" && n.value === str(name)));
        if (c) piaSet(c.children!, "value", value);
    };
    setCustom("View_New_File", bool(false));
    setCustom("Rasterize_Geometry", bool(false));
    return pc3;
}

// ---------------------------------------------------------------- main

export const CONFIG_FILES = {
    pngPc3: join(PLOTTERS_DIR, PNG_PC3),
    pngPmp: join(PMP_DIR, PNG_PMP),
    pdfPc3: join(PLOTTERS_DIR, PDF_PC3),
    pdfPmp: join(PMP_DIR, PDF_PMP),
    monochromeCtb: join(PLOT_STYLES_DIR, "monochrome.ctb"),
    acadCtb: join(PLOT_STYLES_DIR, "acad.ctb"),
} as const;

export function sha256File(p: string): string | null {
    return existsSync(p) ? createHash("sha256").update(readFileSync(p)).digest("hex") : null;
}

function main() {
    const dry = process.argv.includes("--dry-run");
    const dump = process.argv.includes("--dump");
    const stockPngPc3 = read(join(PLOTTERS_DIR, "PublishToWeb PNG.pc3"));
    const stockPngPmp = read(join(PMP_DIR, "PublishToWeb PNG.pmp"));
    const stockPdfPc3 = read(join(PLOTTERS_DIR, "DWG To PDF.pc3"));

    const out: [string, PiaNode[]][] = [
        [CONFIG_FILES.pngPmp, buildPngPmp(stockPngPmp, CONFIG_FILES.pngPmp)],
        [CONFIG_FILES.pngPc3, buildPngPc3(stockPngPc3, CONFIG_FILES.pngPmp)],
        [CONFIG_FILES.pdfPmp, buildPdfPmp(stockPdfPc3, stockPngPmp, CONFIG_FILES.pdfPmp)],
        [CONFIG_FILES.pdfPc3, buildPdfPc3(stockPdfPc3, CONFIG_FILES.pdfPmp)],
    ];
    if (!dry) mkdirSync(PMP_DIR, { recursive: true });
    for (const [path, tree] of out) {
        const text = formatPiaText(tree);
        if (dump) console.log(`===== ${path}\n${text}`);
        if (!dry) writeFileSync(path, encodePia("PC3", text));
    }
    const stock = {
        "PublishToWeb PNG.pc3": sha256File(join(PLOTTERS_DIR, "PublishToWeb PNG.pc3")),
        "PublishToWeb PNG.pmp": sha256File(join(PMP_DIR, "PublishToWeb PNG.pmp")),
        "DWG To PDF.pc3": sha256File(join(PLOTTERS_DIR, "DWG To PDF.pc3")),
    };
    const generated = Object.fromEntries(Object.entries(CONFIG_FILES).map(([k, p]) => [k, sha256File(p)]));
    console.log(JSON.stringify({ written: !dry, plotters: PLOTTERS_DIR, stock, generated }, null, 2));
}

